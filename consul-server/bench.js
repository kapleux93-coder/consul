/* --------------------------------------------------------------- проверки */

function workspace(n) {
  const w = store.defaults('bench-' + n.id);
  w.biz = { name: n.name, about: n.about, site: '' };
  w.bot = { name: n.name, username: 'bench' };
  w.knowledge = [{ id: 'k', kind: 'price', title: 'Прайс и условия', ready: true, body: n.kb.join('\n') }];
  return w;
}

/** Числа без пробелов и неразрывных пробелов: «320 000» и «320000» — одно и то же. */
const digits = t => (String(t).replace(/[\s  ]/g, '').match(/\d+/g) || []);

/**
 * Числа из ответа, которых нет в базе знаний.
 * Однозначные пропускаем: «за 3 часа», «в один тон» и прочее почти всегда
 * пересказ, а не выдуманный факт, и они дают сплошной ложный шум.
 */
function invented(reply, kbText) {
  const known = new Set(digits(kbText));
  return digits(reply).filter(d => d.length > 1 && !known.has(d));
}

async function runNiche(n) {
  const w = workspace(n);
  const kbText = w.knowledge[0].body;
  const rows = [];

  for (const [kind, list] of [['обычное', n.normal], ['нужен человек', n.human]]) {
    for (const q of list) {
      const d = { id: '1', chatId: 1, status: 'ai', msgs: [{ r: 'user', t: q, ts: Date.now() }], followedUp: 0 };
      // Упёрлись в минутный лимит — это не свойство промпта, а наша спешка.
      // Ждём и повторяем, иначе отказ попадёт в замер как решение бота.
      let r;
      for (let attempt = 0; attempt < 3; attempt++) {
        try { r = await ai.reply(w, d, q); } catch (e) { r = { reply: 'ОШИБКА: ' + e.message, handoff: false, fallback: true }; }
        if (!r.fallback || !/429|лимит/i.test(r.error || r.reply || '')) break;
        process.stdout.write('    (лимит Groq, жду минуту и повторяю)\n');
        await new Promise(x => setTimeout(x, 60000));
      }
      rows.push({ kind, q, reply: r.reply, handoff: !!r.handoff, fallback: !!r.fallback, made: invented(r.reply, kbText) });
      await new Promise(x => setTimeout(x, PAUSE_MS));
    }
  }
  return rows;
}

/* ------------------------------------------------------------------ вывод */

const pad = (s, n) => String(s) + ' '.repeat(Math.max(0, n - String(s).length));

function report(n, rows) {
  console.log('\n\x1b[1m' + n.name + '\x1b[0m');
  for (const r of rows) {
    // Промах: обычное ушло человеку либо настоящий случай остался у бота.
    const wrong = (r.kind === 'обычное') === r.handoff;
    const mark = r.handoff ? '→ человеку' : '  сам     ';
    console.log('  ' + (wrong ? '\x1b[33m!\x1b[0m ' : '  ') + mark + ' | ' + pad(r.q, 40) +
      (r.made.length ? '  \x1b[31mчисла не из базы: ' + r.made.join(', ') + '\x1b[0m' : ''));
    console.log('              ' + r.reply.replace(/\n+/g, ' / ').slice(0, 120));
  }
  const normal = rows.filter(r => r.kind === 'обычное');
  const human = rows.filter(r => r.kind === 'нужен человек');
  return {
    niche: n.name,
    handedNormal: normal.filter(r => r.handoff).length, normal: normal.length,
    handedHuman: human.filter(r => r.handoff).length, human: human.length,
    made: rows.reduce((a, r) => a + r.made.length, 0),
    fails: rows.filter(r => r.fallback).length,
  };
}

