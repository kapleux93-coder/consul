function page(title, body) {
  return `<!doctype html><html lang="ru"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>${esc(title)} — Consul</title><style>${CSS}</style></head>
<body><div class="wrap">${body}
<div class="foot">Consul — сервис AI-менеджера для Telegram-ботов.
 <a href="/privacy">Политика данных</a> · <a href="/terms">Условия</a></div>
</div></body></html>`;
}

/** Кто отвечает за сервис. Пока не заполнено — честно об этом говорим. */
function operator() {
  const name = (process.env.OPERATOR_NAME || '').trim();
  const email = (process.env.OPERATOR_EMAIL || '').trim();
  if (name && email) {
    // Имя часто заканчивается точкой сокращения («ИП Иванов И.») — не удваиваем её.
    return `<p><strong>Оператор сервиса:</strong> ${esc(name)}<br>
      Связь по любым вопросам, включая удаление данных:
      <a href="mailto:${esc(email)}">${esc(email)}</a></p>`;
  }
  return `<div class="note warn"><p style="margin:0"><strong>Оператор не указан.</strong>
    Задайте переменные окружения <code>OPERATOR_NAME</code> и <code>OPERATOR_EMAIL</code> —
    без них документ не имеет силы, и приложение не показывает на него ссылку.</p></div>`;
}

/** Настроен ли сервис настолько, чтобы ссылаться на эти страницы из мини-аппа. */
function ready() {
  return !!((process.env.OPERATOR_NAME || '').trim() && (process.env.OPERATOR_EMAIL || '').trim());
}

