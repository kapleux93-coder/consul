'use strict';
/* ============================================================================
 * Политика данных и условия использования — страницы, которые сервис обязан
 * показать до того, как человек отдаст ему токен своего бота.
 *
 * Держим их здесь, а не отдельным хостингом, по двум причинам: они должны
 * жить на том же домене, что и мини-апп (иначе Telegram открывает их во
 * внешнем браузере с предупреждением), и они должны меняться вместе с кодом —
 * текст описывает то, что сервер реально делает, и врать ему нельзя.
 *
 * Всё, что здесь написано, проверено по коду:
 *   • токен бота шифруется AES-256-GCM (secret.js) и наружу не отдаётся;
 *   • переписка клиентов уходит в Groq для генерации ответа (groq.js);
 *   • в диалоге хранятся последние 300 сообщений (store.js);
 *   • владелец удаляет кабинет целиком из приложения (POST /api/account/delete).
 * Меняете поведение — правьте и текст.
 *
 * Юридическую проверку это не заменяет. Оператора (кто отвечает за сервис и
 * куда писать) подставляем из OPERATOR_NAME и OPERATOR_EMAIL: без них ссылки
 * на эти страницы в приложении не показываются — документ без ответственного
 * лица бесполезен.
 * ========================================================================== */

const esc = s => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const UPDATED = '6 сентября 2026 года';

/* ------------------------------------------------------------------ вёрстка */

